/* 校验: 事件须有完整头尾介绍与相关选项 */
(function validateEvents() {
  const FXT = ['pick', 'cards', 'revivePick', 'reviveRandom', 'hpAllChance', 'atkAllChance', 'qi', 'generalHp', 'enemyNext', 'curse', 'sacrificeForCards', 'transform', 'hpForAtk', 'consume', 'log', 'ambush'];
  for (const e of EVENTS) {
    if (!e.id || !e.title || !e.intro || e.intro.length < 20) throw new Error('事件缺头尾介绍: ' + (e.id || '?'));
    if (!Array.isArray(e.opts) || e.opts.length < 2 || e.opts.length > 4) throw new Error('事件选项数量异常: ' + e.id);
    for (const o of e.opts) {
      if (!o.label || !o.desc) throw new Error('事件选项缺文案: ' + e.id);
      for (const fx of (o.fx || [])) {
        if (FXT.indexOf(fx.t) < 0) throw new Error('事件效果类型非法: ' + e.id + ' / ' + fx.t);
        if (fx.t === 'ambush' && o.fx.indexOf(fx) !== o.fx.length - 1) throw new Error('ambush 必须是最后一项: ' + e.id);
      }
    }
  }
})();
